"""App icon and splash generator (R1-release). Dev-side only; nothing here ships.

One original design, drawn from the geometry below: a white speech bubble holding five
waveform bars, on the theme's navy seed colour (#1F4E79, lib/ui/theme/app_theme.dart).
The same shapes are written as

  * store/icon/icon.svg, the master artwork (1024 x 1024, full bleed),
  * Android vector drawables: adaptive-icon foreground and monochrome layers, the
    notification icon (white silhouette, bars cut out) and the splash logo,
  * PNGs rendered with Pillow (MIT-CMU licence): legacy Android launcher icons, the
    iOS AppIcon set (opaque, no alpha), the iOS launch image and the store icons.

Regenerate after changing the design (the generated files are committed):

    python -m tools.release.icons            # from the repo root
    python -m tools.release.icons --check    # fail if a generated file is stale
"""

from __future__ import annotations

import argparse
import io
import json
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw

NAVY = "#1F4E79"
WHITE = "#FFFFFF"

# Adaptive-icon canvas: 108 x 108 units. Launchers show the middle 72 units and mask
# anything outside a 66-unit circle, so the artwork stays inside it.
CANVAS = 108.0
# Full-bleed icons (iOS, legacy Android, store) show this square of the canvas, so the
# bubble fills more of the tile.
FULL_BLEED = (18.0, 18.0, 90.0, 90.0)


@dataclass(frozen=True)
class RoundRect:
    """Axis-aligned rectangle with corner radius r, in canvas units."""

    x0: float
    y0: float
    x1: float
    y1: float
    r: float


BUBBLE = RoundRect(28, 30, 80, 70, 12)
# Tail under the bubble's bottom edge: base from x=40 (where the bottom-left corner
# ends) to x=50, tip at (36, 80).
TAIL = ((40.0, 70.0), (36.0, 80.0), (50.0, 70.0))
_BAR_W = 4.4
_BAR_X = (40.0, 47.0, 54.0, 61.0, 68.0)
_BAR_H = (9.0, 19.0, 27.0, 16.0, 8.0)
_BAR_CY = 50.0
BARS = tuple(
    RoundRect(x - _BAR_W / 2, _BAR_CY - h / 2, x + _BAR_W / 2, _BAR_CY + h / 2, _BAR_W / 2)
    for x, h in zip(_BAR_X, _BAR_H, strict=True)
)


def _fmt(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def round_rect_path(rr: RoundRect) -> str:
    """SVG / VectorDrawable path data for a rounded rectangle (clockwise)."""
    x0, y0, x1, y1, r = rr.x0, rr.y0, rr.x1, rr.y1, rr.r
    f = _fmt
    return (
        f"M{f(x0 + r)},{f(y0)} H{f(x1 - r)} A{f(r)},{f(r)} 0 0 1 {f(x1)},{f(y0 + r)} "
        f"V{f(y1 - r)} A{f(r)},{f(r)} 0 0 1 {f(x1 - r)},{f(y1)} "
        f"H{f(x0 + r)} A{f(r)},{f(r)} 0 0 1 {f(x0)},{f(y1 - r)} "
        f"V{f(y0 + r)} A{f(r)},{f(r)} 0 0 1 {f(x0 + r)},{f(y0)} Z"
    )


def bubble_path() -> str:
    """One contour for the bubble and its tail (clockwise), so the silhouette can cut
    the bars out with the even-odd rule without the tail overlapping the bubble."""
    b = BUBBLE
    r = b.r
    (base_l, _), (tip_x, tip_y), (base_r, _) = TAIL
    f = _fmt
    return (
        f"M{f(b.x0 + r)},{f(b.y0)} H{f(b.x1 - r)} A{f(r)},{f(r)} 0 0 1 {f(b.x1)},{f(b.y0 + r)} "
        f"V{f(b.y1 - r)} A{f(r)},{f(r)} 0 0 1 {f(b.x1 - r)},{f(b.y1)} "
        f"H{f(base_r)} L{f(tip_x)},{f(tip_y)} L{f(base_l)},{f(b.y1)} "
        f"H{f(b.x0 + r)} A{f(r)},{f(r)} 0 0 1 {f(b.x0)},{f(b.y1 - r)} "
        f"V{f(b.y0 + r)} A{f(r)},{f(r)} 0 0 1 {f(b.x0 + r)},{f(b.y0)} Z"
    )


def bars_path() -> str:
    """Path data for the five waveform bars."""
    return " ".join(round_rect_path(b) for b in BARS)


# ---------------------------------------------------------------------------- SVG


def master_svg() -> str:
    """The master artwork: full-bleed square, navy background, as the iOS icon."""
    x0, y0, x1, y1 = FULL_BLEED
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- UK Pronunciation Coach app icon. Original artwork for this app; "
        "generated by tools/release/icons.py, do not edit by hand. -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
        f'viewBox="{_fmt(x0)} {_fmt(y0)} {_fmt(x1 - x0)} {_fmt(y1 - y0)}">\n'
        f'  <rect x="{_fmt(x0)}" y="{_fmt(y0)}" width="{_fmt(x1 - x0)}" '
        f'height="{_fmt(y1 - y0)}" fill="{NAVY}"/>\n'
        f'  <path fill="{WHITE}" d="{bubble_path()}"/>\n'
        f'  <path fill="{NAVY}" d="{bars_path()}"/>\n'
        "</svg>\n"
    )


# -------------------------------------------------------------- VectorDrawables

_VD_HEAD = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/release/icons.py; do not edit by hand. -->\n"
)


def _vector(paths: list[tuple[str, str, str]], size_dp: int = 108) -> str:
    body = "".join(
        f'    <path\n        android:fillColor="{color}"\n'
        f'        android:fillType="{fill_type}"\n'
        f'        android:pathData="{data}" />\n'
        for color, fill_type, data in paths
    )
    return (
        _VD_HEAD + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{_fmt(CANVAS)}"\n'
        f'    android:viewportHeight="{_fmt(CANVAS)}">\n' + body + "</vector>\n"
    )


def foreground_vector() -> str:
    """Adaptive-icon foreground: white bubble and tail, navy bars."""
    return _vector(
        [
            (WHITE, "nonZero", bubble_path()),
            (NAVY, "nonZero", bars_path()),
        ]
    )


def silhouette_vector(size_dp: int = 108) -> str:
    """One-colour silhouette with the bars cut out (themed icon, notification)."""
    data = f"{bubble_path()} {bars_path()}"
    # evenOdd: the bars inside the bubble become holes.
    return _vector([(WHITE, "evenOdd", data)], size_dp)


ADAPTIVE_XML = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/release/icons.py; do not edit by hand. -->\n"
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@color/ic_launcher_background" />\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
    "</adaptive-icon>\n"
)

COLORS_XML = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/release/icons.py; do not edit by hand. -->\n"
    "<resources>\n"
    f'    <color name="ic_launcher_background">{NAVY}</color>\n'
    f'    <color name="splash_background">{NAVY}</color>\n'
    "</resources>\n"
)


# --------------------------------------------------------------------- Raster

_SUPERSAMPLE = 4


def render(
    px: int,
    *,
    view: tuple[float, float, float, float] = FULL_BLEED,
    background: str | None = NAVY,
) -> Image.Image:
    """Renders the icon at px x px. background=None gives a transparent tile."""
    big = px * _SUPERSAMPLE
    x0, y0, x1, y1 = view
    scale = big / (x1 - x0)

    def tx(x: float, y: float) -> tuple[float, float]:
        return ((x - x0) * scale, (y - y0) * scale)

    def rr(draw: ImageDraw.ImageDraw, r: RoundRect, fill: str) -> None:
        a = tx(r.x0, r.y0)
        b = tx(r.x1, r.y1)
        draw.rounded_rectangle((a, b), radius=r.r * scale, fill=fill)

    mode = "RGB" if background else "RGBA"
    img = Image.new(mode, (big, big), background or (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    rr(draw, BUBBLE, WHITE)
    # Raise the tail's base by half a unit so it joins the bubble without a seam.
    draw.polygon([tx(x, y - 0.5 if y == BUBBLE.y1 else y) for x, y in TAIL], fill=WHITE)
    for bar in BARS:
        rr(draw, bar, NAVY)
    return img.resize((px, px), Image.Resampling.LANCZOS)


def png_bytes(img: Image.Image) -> bytes:
    """Deterministic PNG encoding (no metadata, fixed compression)."""
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


# ------------------------------------------------------------------ Outputs

ANDROID_LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
LAUNCH_IMAGE_PT = 120  # iOS launch logo, points (1x, 2x, 3x)


def ios_icon_sizes(contents_json: str) -> dict[str, int]:
    """filename -> pixel size from an AppIcon.appiconset/Contents.json."""
    out = {}
    for image in json.loads(contents_json)["images"]:
        if "filename" not in image:
            continue
        points = float(image["size"].split("x")[0])
        scale = int(image["scale"].rstrip("x"))
        out[image["filename"]] = round(points * scale)
    return out


def outputs(root: Path) -> dict[Path, Callable[[], bytes]]:
    """Every generated file and how to make its bytes."""
    res = root / "android/app/src/main/res"
    files: dict[Path, Callable[[], bytes]] = {
        root / "store/icon/icon.svg": lambda: master_svg().encode(),
        root / "store/icon/icon-1024.png": lambda: png_bytes(render(1024)),
        # Google Play listing icon: 512 x 512, 32-bit PNG.
        root / "store/icon/play-icon-512.png": lambda: png_bytes(render(512).convert("RGBA")),
        res / "drawable/ic_launcher_foreground.xml": lambda: foreground_vector().encode(),
        res / "drawable/ic_launcher_monochrome.xml": lambda: silhouette_vector().encode(),
        res / "drawable/ic_notification.xml": lambda: silhouette_vector(24).encode(),
        res / "mipmap-anydpi-v26/ic_launcher.xml": lambda: ADAPTIVE_XML.encode(),
        res / "values/icon_colors.xml": lambda: COLORS_XML.encode(),
    }
    for density, px in ANDROID_LEGACY.items():
        files[res / f"mipmap-{density}/ic_launcher.png"] = lambda px=px: png_bytes(render(px))

    appicon = root / "ios/Runner/Assets.xcassets/AppIcon.appiconset"
    contents = (appicon / "Contents.json").read_text(encoding="utf-8")
    for name, px in ios_icon_sizes(contents).items():
        # App Store rejects icons with an alpha channel: RGB only.
        files[appicon / name] = lambda px=px: png_bytes(render(px))

    launch = root / "ios/Runner/Assets.xcassets/LaunchImage.imageset"
    for suffix, scale in (("", 1), ("@2x", 2), ("@3x", 3)):
        files[launch / f"LaunchImage{suffix}.png"] = lambda s=scale: png_bytes(
            render(LAUNCH_IMAGE_PT * s, view=(26, 26, 82, 82), background=None)
        )
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--check", action="store_true", help="fail if any file is stale")
    args = parser.parse_args(argv)
    stale = []
    for path, make in outputs(args.root).items():
        data = make()
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if args.check and stale:
        print("Stale icon files (run python -m tools.release.icons):", file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    print(f"{len(stale)} file(s) {'stale' if args.check else 'written'}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
