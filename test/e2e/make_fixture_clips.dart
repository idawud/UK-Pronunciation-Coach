// Writes integration_test/e2e/fixture_clips.dart from test/e2e/fixtures/*.wav:
// a device cannot read test/, so the on-device journey embeds the clips as
// base64. Run after changing a clip (test/e2e/fixture_clips_test.dart checks it):
//
//   dart run test/e2e/make_fixture_clips.dart
import 'dart:convert';
import 'dart:io';

const clipsDir = 'test/e2e/fixtures';
const outFile = 'integration_test/e2e/fixture_clips.dart';

/// The generated Dart source for the clips in [clipsDir].
String fixtureClipsSource() {
  final files =
      Directory(clipsDir)
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.wav'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln('// Generated by test/e2e/make_fixture_clips.dart from')
    ..writeln(
      '// $clipsDir/*.wav (see test/e2e/fixtures/README.md). Do not edit.',
    )
    ..writeln('// dart format off')
    ..writeln()
    ..writeln('/// Fixture WAVs (16 kHz mono PCM16) by file name, base64.')
    ..writeln('const Map<String, String> fixtureClipsBase64 = {');
  for (final f in files) {
    final name = f.uri.pathSegments.last;
    final b64 = base64Encode(f.readAsBytesSync());
    out.writeln("  '$name':");
    for (var i = 0; i < b64.length; i += 76) {
      final end = i + 76 < b64.length ? i + 76 : b64.length;
      final last = end == b64.length;
      out.writeln("      '${b64.substring(i, end)}'${last ? ',' : ''}");
    }
  }
  out.writeln('};');
  return out.toString();
}

void main() => File(outFile).writeAsStringSync(fixtureClipsSource());
